const assert = require('node:assert/strict');
const api = require('../assets/site.js');
const fs = require('node:fs');
const content = JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'../content.json'),'utf8'));
const items = content.PROJECTS.map((p,index) => ({title:p.title,search:p.title+' '+p.summary+' '+p.kind,tags:p.tags,year:p.year,type:index<3?'research':'field',index}));
const base = {theme:'Tous',query:'',type:'all',sort:'newest'};
const visible = state => items.filter(item=>api.matches(item,{...base,...state}));
assert.equal(visible({}).length,4);
assert.equal(visible({theme:'Finance'}).length,1);
assert.equal(visible({theme:'Données',type:'field'}).length,1);
assert.equal(visible({theme:'Finance',type:'field'}).length,0);
assert.equal(visible({query:'ECONOMIES CEDEAO'}).length,1);
assert.equal(visible({query:'nonexistent-topic'}).length,0);
assert.equal(visible({query:'irrigation securite'}).length,1);
assert.equal(api.order(items,'oldest','fr')[0].year,'2023');
assert.equal(api.order(items,'newest','fr')[0].year,'2026');
assert.deepEqual(api.order(items,'title','fr').map(item=>item.title),[items[1].title,items[0].title,items[3].title,items[2].title]);
assert.equal(items[0].title,content.PROJECTS[0].title); // Sorting must not mutate source order.
const loaded=api.readState(new URLSearchParams('theme=Finance&q=secteurs&type=research&sort=oldest'),['Tous','Finance'],['all','research']);
assert.deepEqual(loaded,{theme:'Finance',query:'secteurs',type:'research',sort:'oldest'});
assert.deepEqual(api.readState(new URLSearchParams('theme=Invalid&type=wrong&sort=wrong'),['Tous'],['all']),base);
const written=api.writeState('https://example.test/projets/?campaign=x#main',loaded);
const restored=api.readState(new URL(written,'https://example.test').searchParams,['Tous','Finance'],['all','research']);
assert.deepEqual(restored,loaded);
assert.equal(api.writeState('https://example.test/projets/?theme=Finance&q=test&type=research&sort=oldest',base),'/projets/');
const email=api.prepareEmail('emmanuelakounna@gmail.com',{name:'Aïcha Test',organisation:'Research & Development',reason:'Analyse de données',message:'Une étude de données\nBudget & échéance : à préciser.'},false);
assert.ok(email.href.startsWith('mailto:emmanuelakounna@gmail.com?subject='));
const mail=new URL(email.href);
assert.equal(mail.searchParams.get('subject'),'Proposition de collaboration — Analyse de données');
assert.ok(mail.searchParams.get('body').includes('Budget & échéance'));
assert.ok(mail.searchParams.get('body').endsWith('Aïcha Test\nResearch & Development'));
assert.ok(api.prepareEmail('test@example.com',{name:'Test',organisation:'',reason:'Research',message:'Discuss a research project.'},true).body.startsWith('Hello Hugues,'));
console.log('PASS: combined filters, accent-insensitive search, sorting, URL state/reset and bilingual email drafts.');
